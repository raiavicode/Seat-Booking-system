"""
Lock Slot Lambda -- Arrow 9 (Step Functions -> Lock Slot) and Arrow 11
(Lock Slot -> DynamoDB, writing PENDING status)

THIS FUNCTION *IS* THE ARROW-11 RELIABILITY FIX.
The ConditionExpression below is what makes locking atomic across
concurrent requests. Without it, two Lambdas racing to lock the same seat
would both succeed (a plain PutItem/UpdateItem has no idea another request
is in flight) -- WITH it, DynamoDB itself rejects the second writer with a
ConditionalCheckFailedException, atomically, no separate lock service
required.
"""

import os
import time
import boto3
from botocore.exceptions import ClientError

TABLE_NAME = os.environ["SLOTS_TABLE_NAME"]
# How long a PENDING lock is honored before it's considered abandoned
# (e.g. the user closed the tab mid-checkout). The EventBridge timeout
# rule (Arrow 21) uses this same value to decide when to fire the backup
# release -- keep these in sync if you change one.
LOCK_TTL_SECONDS = int(os.environ.get("LOCK_TTL_SECONDS", "600"))

dynamodb = boto3.resource("dynamodb")
table = dynamodb.Table(TABLE_NAME)


def handler(event, context):
    event_id = event["event_id"]
    slot_id = event["slot_id"]
    booking_id = event["booking_id"]  # generated by the caller (Step Functions execution ID is a good choice)

    now = int(time.time())

    try:
        table.update_item(
            Key={"event_id": event_id, "slot_id": slot_id},
            UpdateExpression=(
                "SET #status = :pending, "
                "booking_id = :booking_id, "
                "locked_at = :now, "
                "expires_at = :expires"
            ),
            # THE ACTUAL FIX: only apply this write if the item does not
            # exist yet, OR its current status is already AVAILABLE, OR
            # its previous lock has expired. This is what makes the lock
            # atomic -- DynamoDB evaluates the condition and the update
            # as a single indivisible operation server-side.
            ConditionExpression=(
                "attribute_not_exists(#status) OR "
                "#status = :available OR "
                "expires_at < :now"
            ),
            ExpressionAttributeNames={"#status": "status"},
            ExpressionAttributeValues={
                ":pending": "PENDING",
                ":available": "AVAILABLE",
                ":booking_id": booking_id,
                ":now": now,
                ":expires": now + LOCK_TTL_SECONDS,
            },
        )
    except ClientError as e:
        if e.response["Error"]["Code"] == "ConditionalCheckFailedException":
            # Someone else already holds a valid lock on this seat.
            # Step Functions' Catch block should route this to a
            # "seat unavailable" response, NOT to the Release Lock
            # compensation path -- there's nothing for us to release,
            # we never acquired anything.
            return {"locked": False, "reason": "SEAT_ALREADY_LOCKED"}
        raise

    return {"locked": True, "event_id": event_id, "slot_id": slot_id, "booking_id": booking_id}
